# ดึงคอลัมน์จริงจาก DDL — ห้ามเขียนรายชื่อคอลัมน์มือ
# ---------------------------------------------------------------------------
_SKIP_PREFIX = ("CONSTRAINT", "PRIMARY", "UNIQUE", "CHECK", "FOREIGN")


def ddl_columns_by_table() -> dict[str, list[tuple[str, str]]]:
    """{ตาราง: [(ชื่อคอลัมน์, ชนิด), ...]} อ่านสดจาก DDL ของ build_lldd_documents"""
    from build_lldd_documents import database_ddl_sections

    out: dict[str, list[tuple[str, str]]] = {}
    for title, body in database_ddl_sections():
        if "Index" in title:
            continue
        for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\);", body, re.S):
            cols: list[tuple[str, str]] = []
            depth, buf, parts = 0, "", []
            for ch in re.sub(r"--[^\n]*", "", m.group(2)):
                if ch == "(":
                    depth += 1
                if ch == ")":
                    depth -= 1
                if ch == "," and depth == 0:
                    parts.append(buf)
                    buf = ""
                else:
                    buf += ch
            parts.append(buf)
            for part in parts:
                text = " ".join(part.split())
                if not text or text.upper().startswith(_SKIP_PREFIX):
                    continue
                cm = re.match(r"([a-z_][a-z0-9_]*)\s+([A-Za-z]+(?:\([\d, ]+\))?)", text)
                if cm:
                    cols.append((cm.group(1), cm.group(2)))
            out[m.group(1)] = cols
    return out


def column_doc(table: str, column: str) -> tuple[str, str] | None:
    """คำอธิบายของคอลัมน์ — ดูของเฉพาะตารางก่อน แล้วค่อย fallback ไปคอลัมน์มาตรฐาน"""
    own = TABLE_DOCS.get(table, {}).get("columns", {})
    if column in own:
        return own[column]
    return COMMON_COLUMNS.get(column)


def coverage_gaps() -> list[str]:
    """ช่องว่างของพจนานุกรม — ใช้โดย tools/check_docs.py กฎ #88"""
    gaps: list[str] = []
    ddl = ddl_columns_by_table()
    for table in sorted(ddl):
        if table not in TABLE_DOCS:
            gaps.append(f"{table} :: มีใน DDL แต่ไม่มีคำอธิบายระดับตารางในพจนานุกรม")
            continue
        real = {c for c, _ in ddl[table]}
        for col, _ in ddl[table]:
            if column_doc(table, col) is None:
                gaps.append(f"{table}.{col} :: มีใน DDL แต่ไม่มีคำอธิบายรายคอลัมน์")
        for col in sorted(TABLE_DOCS[table].get("columns", {})):
            if col not in real:
                gaps.append(f"{table}.{col} :: อธิบายไว้ในพจนานุกรม แต่ไม่มีคอลัมน์นี้ใน DDL")
    for table in sorted(TABLE_DOCS):
        if table not in ddl:
            gaps.append(f"{table} :: อยู่ในพจนานุกรม แต่ไม่มี CREATE TABLE ใน DDL")
    return gaps


