K2_STATUS_DONE = "09"                              # เสร็จสิ้นดำเนินการ → SGI '99'
SGI_STATUS_DONE = "99"
SGI_LIVE_STATUS = ("01", "02", "03", "06", "08")   # สถานะ "รอ…" ที่ SGI มีจริง
SGI_SECTIONS = ("01", "02", "03", "06", "08")      # ขั้นที่ SGI มีจริง (ไม่มี 04/05/07/09/10)


def _in(values: tuple[str, ...]) -> str:
    return "(" + ", ".join(f"'{v}'" for v in values) + ")"


def doc_migratable(alias: str = "f") -> str:
    """เงื่อนไข "เอกสารนี้ย้ายได้" — **แหล่งเดียว** ใช้ซ้ำทั้งใน INSERT และในตัวนับ

    เขียนไว้ที่เดียวเพราะรอบที่แล้วเงื่อนไขใน INSERT กับในตัวนับ *เหมือนกัน* จึงไม่มีอะไรจับได้
    ว่าเงื่อนไขนั้นเองตัดข้อมูลทิ้ง — ตัวนับยืนยันความผิดของตัวเอง
    """
    return (f"{alias}.comp_document_id ~ '^[0-9]{{4}}/[0-9]{{5}}$'\n"
            f"   AND ({alias}.comp_status_code = '{K2_STATUS_DONE}'\n"
            f"        OR ({alias}.comp_status_code IN {_in(SGI_LIVE_STATUS)}\n"
            f"            AND {alias}.comp_section_code IN {_in(SGI_SECTIONS)}))")


