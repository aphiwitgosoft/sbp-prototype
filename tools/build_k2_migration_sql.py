def dump_files() -> list[tuple[str, Path]]:
    out = []
    for p in sorted(DUMP.glob("data_*.csv")):
        m = re.fullmatch(r"data_(.+)_\d{8}\.csv", p.name)
        if m:
            out.append((m.group(1), p))
    return out


def header_of(p: Path) -> list[str]:
    with p.open(encoding="utf-8-sig", newline="") as fh:
        return next(csv.reader(fh))


def count_rows(p: Path) -> int:
    with p.open(encoding="utf-8-sig", newline="") as fh:
        r = csv.reader(fh)
        next(r, None)
        return sum(1 for _ in r)


def snake(name: str) -> str:
    """CompDocumentID → comp_document_id (PostgreSQL ไม่ชอบ CamelCase ที่ไม่ได้ quote)"""
    s = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.lower()


def q(name: str) -> str:
    """ครอบ identifier ด้วย double quote เสมอ

    🔴 จำเป็นจริง — `CommonConfig` มีคอลัมน์ชื่อ `Group` ซึ่งเป็น **คำสงวนของ PostgreSQL**
       ถ้าไม่ quote จะได้ `syntax error at or near "group"` ตอน CREATE TABLE
       (เจอตอนรันจริงกับฐาน dev 2026-09-16) · quote ทุกตัวปลอดภัยกว่าไล่ดักเป็นราย ๆ
    """
    return '"' + snake(name).replace('"', '""') + '"'


def ora_tables() -> list[tuple[str, list[str]]]:
    """อ่านโครงตารางฝั่ง Oracle จาก output/legacy-oracle/schema.sql"""
    if not ORA_SCHEMA.exists():
        return []
    txt = ORA_SCHEMA.read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\);", txt, re.S):
        name, body = m.group(1), m.group(2)
        if name not in ORA_NEEDED:
            continue
        cols = [c for c in re.findall(r"^    ([A-Z][A-Z_0-9]*)\s", body, re.M) if c != "CONSTRAINT"]
        out.append((name, cols))
    return sorted(out)


def ora_counts() -> dict:
    import json
    if not ORA_DATA.exists():
        return {}
    return json.loads(ORA_DATA.read_text(encoding="utf-8")).get("data", {}).get("row_counts", {})


def build_ora_stage(tables: list[tuple[str, list[str]]], counts: dict) -> str:
    """ขั้นที่ 1b — ตารางพักฝั่ง Oracle FCS_FRN (โซน A)

    🔴 แก้ 2026-09-17 หลัง review — ของเดิมโหลดข้อมูลไม่ได้เลย 3 เหตุ:
      1. คำสั่ง \\copy ทุกบรรทัดเป็น comment → รันแล้วได้ตารางว่างแต่ "สำเร็จ"
      2. `src TEXT NOT NULL DEFAULT 'LIVE'` ชนกับ `UPDATE … WHERE src IS NULL`
         ที่ตามมา — DEFAULT เติม 'LIVE' ให้แล้ว WHERE จึงไม่มีวัน match
      3. ไม่มีคำสั่งโหลดฝั่ง backup (`*_BK_20250515`) และไม่มีทางตั้ง src='BK'
         ทั้งที่ประวัติส่วนใหญ่อยู่ในตาราง backup (FGI_IMPACT_STORE live 728 / bk 26,264)
    """
    L: list[str] = []
    a = L.append
    a("-- =====================================================================")
    a("--  ขั้นที่ 1b · พักข้อมูลฝั่ง **Oracle FCS_FRN (โซน A)** ไว้ในฐาน SGI dev")
    a("--  สร้างจาก tools/build_k2_migration_sql.py — **ห้ามแก้ไฟล์นี้ด้วยมือ**")
    a("-- ---------------------------------------------------------------------")
    a(f"--  {len(tables)} ตารางที่ migration ต้องใช้ · โครงอ่านจาก output/legacy-oracle/schema.sql")
    a("--")
    a("--  🔴 **ยังไม่มีข้อมูลแถวจริง** — `output/legacy-oracle/` มีแค่ schema + สถิติ + โดเมน")
    a("--     (`tools/introspect_legacy_oracle.py` เป็น SELECT ล้วนที่สกัด *สถิติ* ไม่ได้ dump แถว)")
    a("--     ต้องขอ dump แถวจริงจากทีมเจ้าของ Oracle ในรูปแบบ CSV เหมือนฝั่ง K2")
    a("--")
    a("--  วิธีรัน — ต้องมีไฟล์ CSV ครบก่อน แล้วชี้ :dump ไปที่โฟลเดอร์นั้น")
    a("--     psql -v dump=/path/to/oracle_csv -f k2_migration_1b_stage_oracle.sql")
    a("--  ⚠️ **ไม่มีไฟล์ = ล้มทันทีที่ \\copy บรรทัดแรก** ซึ่งเป็นพฤติกรรมที่ตั้งใจ")
    a("--     ดีกว่ารันผ่านเงียบ ๆ แล้วเข้าใจผิดว่าโหลดข้อมูลแล้ว (บั๊กของเวอร์ชันก่อน)")
    a("--")
    a("--  ทุกคอลัมน์เป็น TEXT ด้วยเหตุผลเดียวกับฝั่ง K2 — โหลดให้เข้าครบก่อน แล้วค่อยตรวจ/แปลง")
    a("--  `src` แยก 'LIVE' (ตารางปัจจุบัน) ออกจาก 'BK' (`*_BK_20250515` ที่เก็บประวัติ)")
    a("-- =====================================================================")
    a("")
    a("\\set ON_ERROR_STOP on")
    a("")
    a("-- ---------------------------------------------------------------------")
    a("-- preflight — ต้องส่ง :dump มาด้วย ไม่งั้นหยุดทันที")
    a("-- ---------------------------------------------------------------------")
    a("\\if :{?dump}")
    a("\\else")
    a("\\echo '🔴 ต้องระบุโฟลเดอร์ CSV: psql -v dump=/path/to/oracle_csv -f <ไฟล์นี้>'")
    a("\\quit")
    a("\\endif")
    a("")
    a("BEGIN;")
    a("SET search_path TO sps_store;")
    a("")
    a("-- ---------------------------------------------------------------------")
    a("-- 1. สร้างตารางพัก")
    a("--    ⚠️ `src` ตอนสร้าง **ยอมให้ NULL** เพื่อให้ \\copy (ที่ไม่ส่ง src มา) ผ่านได้")
    a("--       แล้วตั้งค่าทันทีหลัง COPY แต่ละรอบ · ปิดท้ายด้วย SET NOT NULL ที่ข้อ 4")
    a("--       **ห้ามใส่ DEFAULT** — DEFAULT จะเติมค่าให้ก่อน ทำให้ WHERE src IS NULL ไม่ match")
    a("--       (นี่คือบั๊กของเวอร์ชันก่อนหน้า ที่ทำให้แถว backup ถูกติดป้ายเป็น LIVE ทั้งหมด)")
    a("-- ---------------------------------------------------------------------")
    for name, cols in tables:
        t = ORA_PREFIX + name.lower()
        live = counts.get(name, "?")
        bk = counts.get(name + "_BK_20250515", "—")
        a(f"-- {name} · live {live} แถว · backup_20250515 {bk} แถว · {len(cols)} คอลัมน์")
        a(f"CREATE TABLE IF NOT EXISTS {t} (")
        a(",\n".join(f"    {q(c)} TEXT" for c in cols) + ",")
        a("    src TEXT   -- 'LIVE' หรือ 'BK' — ตั้งค่าหลัง COPY แต่ละรอบ (ห้ามใส่ DEFAULT)")
        a(");")
        a(f"ALTER TABLE {t} ALTER COLUMN src DROP NOT NULL;   -- เผื่อรันซ้ำบนตารางที่ตั้ง NOT NULL ไปแล้ว")
        a(f"TRUNCATE {t};                                     -- โหลดใหม่ทุกครั้ง ไม่ให้ซ้อนของเก่า")
        a("")
    a("-- ---------------------------------------------------------------------")
    a("-- 2. โหลด **live** แล้วติดป้าย src = 'LIVE' ทันที")
    a("-- ---------------------------------------------------------------------")
    for name, cols in tables:
        t = ORA_PREFIX + name.lower()
        collist = ", ".join(q(c) for c in cols)
        a(f"\\copy {t} ({collist}) FROM :'dump'/{name}.csv WITH (FORMAT csv, HEADER true, NULL 'NULL', ENCODING 'UTF8')")
        a(f"UPDATE {t} SET src = 'LIVE' WHERE src IS NULL;")
        a("")
    a("-- ---------------------------------------------------------------------")
    a("-- 3. โหลด **backup** (`*_BK_20250515`) แล้วติดป้าย src = 'BK'")
    a("--    🔴 ห้ามข้ามขั้นนี้ — ประวัติส่วนใหญ่อยู่ในตาราง backup ไม่ใช่ตาราง live")
    a(f"--       เช่น FGI_IMPACT_STORE live {counts.get('FGI_IMPACT_STORE','?')} แถว "
      f"· backup {counts.get('FGI_IMPACT_STORE_BK_20250515','?')} แถว")
    a("--    โครงคอลัมน์ของ *_BK_20250515 เท่ากับตาราง live (ตรวจจาก schema.sql แล้ว)")
    a("-- ---------------------------------------------------------------------")
    for name, cols in tables:
        t = ORA_PREFIX + name.lower()
        collist = ", ".join(q(c) for c in cols)
        bk = counts.get(name + "_BK_20250515")
        if bk in (None, "—", 0, "0"):
            a(f"-- {name}_BK_20250515 — ไม่มีตาราง backup ฝั่ง Oracle (ข้าม)")
            a("")
            continue
        a(f"\\copy {t} ({collist}) FROM :'dump'/{name}_BK_20250515.csv WITH (FORMAT csv, HEADER true, NULL 'NULL', ENCODING 'UTF8')")
        a(f"UPDATE {t} SET src = 'BK' WHERE src IS NULL;")
        a("")
    a("-- ---------------------------------------------------------------------")
    a("-- 4. ล็อก src แล้ว ANALYZE — **ห้ามข้าม ANALYZE**")
    a("--    (เหตุผลเดียวกับฝั่ง K2 · COPY ไม่อัปเดตสถิติ planner · วัดจริงแล้ว n_live_tup = 0)")
    a("-- ---------------------------------------------------------------------")
    for name, _c in tables:
        t = ORA_PREFIX + name.lower()
        a(f"ALTER TABLE {t} ALTER COLUMN src SET NOT NULL;")
        a(f"CREATE INDEX IF NOT EXISTS idx_{t}_src ON {t}(src);")
        a(f"ANALYZE {t};")
    a("")
    a("-- ---------------------------------------------------------------------")
    a("-- 5. ตรวจจำนวนแถว **แยกตาม src** เทียบกับสถิติที่สกัดมาจาก Oracle")
    a("--    ไม่ตรง = โหลดไม่ครบ หรือได้ไฟล์ผิดงวด → หยุดก่อน COMMIT")
    a("-- ---------------------------------------------------------------------")
    a("DO $$")
    a("DECLARE n bigint; nbk bigint; problems text[] := '{}';")
    a("BEGIN")
    for name, _c in tables:
        t = ORA_PREFIX + name.lower()
        live = counts.get(name)
        bk = counts.get(name + "_BK_20250515")
        a(f"    SELECT count(*) FILTER (WHERE src = 'LIVE'), count(*) FILTER (WHERE src = 'BK')")
        a(f"      INTO n, nbk FROM {t};")
        if isinstance(live, int):
            a(f"    IF n <> {live} THEN")
            a(f"        problems := problems || format('{t} live %s <> {live}', n);")
            a("    END IF;")
        else:
            a(f"    IF n = 0 THEN problems := problems || '{t} live ว่าง'; END IF;")
        if isinstance(bk, int) and bk > 0:
            a(f"    IF nbk <> {bk} THEN")
            a(f"        problems := problems || format('{t} bk %s <> {bk}', nbk);")
            a("    END IF;")
    a("    IF array_length(problems, 1) > 0 THEN")
    a("        RAISE EXCEPTION 'จำนวนแถวไม่ตรงสถิติต้นทาง: %', array_to_string(problems, ' · ');")
    a("    END IF;")
    a("    RAISE NOTICE 'โหลดโซน A ครบทุกตาราง ตรงสถิติต้นทาง';")
    a("END $$;")
    a("")
    a("COMMIT;")
    a("")
    a("-- =====================================================================")
    a("-- ถอนตารางพักฝั่ง Oracle")
    for name, _c in tables:
        a(f"--   DROP TABLE IF EXISTS {ORA_PREFIX + name.lower()};")
    a("-- =====================================================================")
    return "\n".join(L) + "\n"


