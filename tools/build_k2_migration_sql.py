    a("--    ปลายทางเป็น BIGSERIAL แต่ migration ใส่ id มาเอง → sequence ยังค้างที่ 1")
    a("--    ไม่ดัน = application insert แถวถัดไปได้ id 1 แล้ว **ชน primary key ทันที**")
    a("--    ⚠️ setval ได้เพราะเป็น sequence ของตาราง sgi_* ที่เราเป็นเจ้าของ")
    a("--       (ต่างจาก email_template ของทีมอื่นที่ห้ามแตะ — ดู sgi_seed_data.sql)")
    a("-- ---------------------------------------------------------------------")
    a("DO $$")
    a("DECLARE t text; s text; mx bigint;")
    a("BEGIN")
    a("    FOREACH t IN ARRAY ARRAY[" + ", ".join(f"'{x}'" for x in SEQ_FIXUP) + "] LOOP")
    a("        -- ⚠️ ต้องเช็คว่ามีคอลัมน์ id ก่อน — pg_get_serial_sequence **โยน error**")
    a("        --    ไม่ได้คืน NULL ถ้าคอลัมน์ไม่มี (sgi_impacted_stores มี PK เป็น store_code varchar)")
    a("        IF NOT EXISTS (SELECT 1 FROM information_schema.columns")
    a("                        WHERE table_schema = 'sps_store' AND table_name = t")
    a("                          AND column_name = 'id') THEN CONTINUE; END IF;")
    a("        s := pg_get_serial_sequence('sps_store.' || t, 'id');")
    a("        IF s IS NULL THEN CONTINUE; END IF;        -- คอลัมน์ id มี แต่ไม่ได้ผูก sequence")
    a("        EXECUTE format('SELECT max(id) FROM %I', t) INTO mx;")
    a("        IF mx IS NULL THEN")
    a("            PERFORM setval(s, 1, false);           -- ตารางว่าง → แถวถัดไปได้ 1")
    a("            RAISE NOTICE 'sequence % — ตารางว่าง ตั้งให้เริ่มที่ 1', s;")
    a("        ELSE")
    a("            PERFORM setval(s, mx, true);           -- แถวถัดไปได้ mx+1")
    a("            RAISE NOTICE 'sequence % ← % (แถวถัดไปได้ %)', s, mx, mx + 1;")
    a("        END IF;")
    a("    END LOOP;")
    a("END $$;")
