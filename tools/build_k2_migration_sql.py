# ไฟล์แนบที่ฝัง base64 มากับ dump — เงื่อนไข "แกะได้จริง"
#   ต้องปิด </content> ครบ **และ** ความยาว base64 (หลังตัดช่องว่าง) หารด้วย 4 ลงตัว
#   ไม่งั้น decode() ของ PostgreSQL จะ **โยน error ทั้งคำสั่ง** ไม่ใช่คืน NULL
#   (เจอจริง 2026-09-17: 1 แถว padding เสีย ทำให้ทั้ง query ล้ม)
# ---------------------------------------------------------------------
ATTACH_B64 = ("regexp_replace(substring(f.attach_file_link from '<content>(.*)</content>'), "
              "'\\s', '', 'g')")
ATTACH_DECODABLE = (f"f.attach_file_link LIKE '%</content>%'\n"
                    f"        AND {ATTACH_B64} <> ''\n"
                    f"        AND length({ATTACH_B64}) % 4 = 0")


# ตารางที่ migration ใส่ค่า id เองทั้งที่ปลายทางเป็น BIGSERIAL → ต้องดัน sequence ตามหลัง
#   ไม่ทำ = sequence ยังอยู่ที่ 1 · application insert ครั้งถัดไปชน primary key ทันที
#   ⚠️ ทุกตัวเป็น sequence ของตาราง `sgi_*` ซึ่ง **เราเป็นเจ้าของเอง** — ต่างจาก email_template
#      ของทีมอื่นที่ห้าม setval (ดูหมายเหตุใน sgi_seed_data.sql) · ที่นี่ setval ถูกต้องและจำเป็น
SEQ_FIXUP = ["sgi_impacted_stores", "sgi_fgi_impact_processes",
             "sgi_fgi_impact_compensations", "sgi_compensation_documents"]


def build_documents() -> str:
    """ขั้นที่ 3 — แปลงข้อมูลจากตารางพักทั้งสองฝั่งเข้าตารางจริงของ SGI

    เขียนไว้ล่วงหน้าเพื่อให้พร้อมรันทันทีที่ได้ข้อมูลโซน A
    **ยังทดสอบกับข้อมูลจริงครบไม่ได้** — ฝั่ง Oracle ยังไม่มีแถว
    ทุกบล็อกจึงมี WHERE NOT EXISTS และมีตัวนับให้เทียบ
    """
    K = PREFIX          # sgi_mig_k2_
    O = ORA_PREFIX      # sgi_mig_ora_
    L: list[str] = []
    a = L.append
    a("-- =====================================================================")
    a("--  ขั้นที่ 3 · แปลงข้อมูลเข้าตารางจริงของ SGI")
    a("--  สร้างจาก tools/build_k2_migration_sql.py — **ห้ามแก้ไฟล์นี้ด้วยมือ**")
    a("-- ---------------------------------------------------------------------")
    a("--  แหล่งข้อมูล **สองฝั่ง**:")
    a(f"--    {O}*   ← Oracle FCS_FRN (โซน A · การคำนวณ)")
    a(f"--    {K}*    ← SQL Server CPA_FRN_FGI (โซน B · เอกสาร/อนุมัติ)")
    a("--")
    a("--  🔴 **ยังรันไม่ได้จนกว่าจะโหลดข้อมูลโซน A** — preflight หยุดให้เอง")
    a("--  🔴 **ไฟล์นี้ย้ายเฉพาะหัวเอกสาร — ยังไม่ใช่ migration ครบวงจร**")
    a("--     ตารางลูกอีก 10 ตัวยังไม่ได้ย้าย (รายการอยู่ข้อ 5) · **ห้ามใช้ทำ cutover จริง**")
    a("--     จนกว่าข้อ 5 จะเสร็จ ไม่งั้นเอกสารจะไม่มีประวัติ/ไฟล์แนบ/ร้านใหม่/คู่แข่ง")
    a("--")
    a("--  ลำดับตาม dependency ของ FK — **ห้ามสลับ**")
    a("--    1 sgi_impacted_stores → 2 sgi_fgi_impact_processes → 3 sgi_fgi_impact_compensations")
    a("--    → 4 sgi_compensation_documents → 5 ตารางลูก → 6 ดัน sequence → 7 ตรวจผล")
    a("-- =====================================================================")
    a("")
    a("\\set ON_ERROR_STOP on")
    a("")
    a("BEGIN;")
    a("SET search_path TO sps_store;")
    a("")
    a("-- ---------------------------------------------------------------------")
    a("-- preflight — ต้องมีข้อมูลทั้งสองฝั่งก่อน")
    a("--   🔴 cutover ต้อง **หยุด writer ทุกตัวก่อน** (API + batch job ทั้ง 12)")
    a("--      ไฟล์นี้ใส่ id เองแล้วดัน sequence ตามหลัง (ข้อ 6) — ถ้ามี writer insert คั่นกลาง")
    a("--      sequence จะถูกดันข้ามแถวของ writer แล้วชน primary key ทีหลัง")
    a("-- ---------------------------------------------------------------------")
    a("DO $$")
    a("DECLARE n bigint;")
    a("BEGIN")
    for t in ("fgi_impact_store_on_process", "fgi_impact_store", "fgi_impact_store_compensate"):
        a(f"    IF to_regclass('sps_store.{O}{t}') IS NULL THEN")
        a(f"        RAISE EXCEPTION 'ยังไม่มีตารางพัก {O}{t} — รัน k2_migration_1b_stage_oracle.sql ก่อน';")
        a("    END IF;")
        a(f"    EXECUTE 'SELECT count(*) FROM {O}{t}' INTO n;")
        a(f"    IF n = 0 THEN RAISE EXCEPTION 'ตารางพัก {O}{t} ว่าง — ยังไม่ได้โหลดข้อมูลโซน A'; END IF;")
    a(f"    SELECT count(*) INTO n FROM {K}compensate_flow;")
    a(f"    IF n = 0 THEN RAISE EXCEPTION 'ตารางพัก {K}compensate_flow ว่าง — รัน k2_migration_1_stage.sql ก่อน'; END IF;")
    a("END $$;")
    a("")

    a("-- ---------------------------------------------------------------------")
    a("-- 1. sgi_impacted_stores ← ร้านที่ถูกกระทบ (distinct จากฝั่ง Oracle)")
    a("--    ⚠️ lpad 5 หลัก — ข้อมูลเดิมเสียศูนย์นำหน้าได้ (เจอจริงฝั่ง K2 แล้ว)")
    a("--    dv_code / transfer_sbp_date มาจาก FGI_IMPACT_STORE_INFO ที่มีข้อมูลผู้ดูแลร้าน")
    a("-- ---------------------------------------------------------------------")
    a("INSERT INTO sgi_impacted_stores (store_code, dv_code, transfer_sbp_date, is_active)")
    a("SELECT lpad(btrim(x.storecode_i), 5, '0'),")
    a("       max(nullif(btrim(i.dv_emp_id), '')),")
    a("       max(nullif(btrim(i.sbp_transfer_date_i), ''))::date,")
    a("       TRUE")
    a(f"  FROM {O}fgi_impact_store x")
    a(f"  LEFT JOIN {O}fgi_impact_store_info i")
    a("         ON btrim(i.storecode_i) = btrim(x.storecode_i)")
    a(" WHERE x.storecode_i IS NOT NULL AND btrim(x.storecode_i) <> ''")
    a(" GROUP BY lpad(btrim(x.storecode_i), 5, '0')")
    a("    ON CONFLICT (store_code) DO NOTHING;")
    a("")

    a("-- ---------------------------------------------------------------------")
    a("-- 2. sgi_fgi_impact_processes ← FGI_IMPACT_STORE_ON_PROCESS")
    a("--    🔴 impact_month/impact_year ใช้ START_COMPENSATE_* (มติ DECISIONS 2.38(3))")
    a("--       **ห้ามใช้ LAST_COMPENSATE_*** ที่เลื่อนไปแล้ว 49.6% ของแถว")
    a("--    ⚠️ process_status ของเดิมไม่มี — ตั้งตามสถานะปลายทางที่เหมาะสม ต้องให้ธุรกิจยืนยัน")
    a("--    ⚠️ ใส่ id เอง → ต้องดัน sequence ที่ข้อ 6")
    a("--")
    a("--    🔴 **กติกาตัดแถวแม่ที่ซ้ำ** (เพิ่ม 2026-09-17 · มติ 2.38-2 · LLDD-BE-Data-Migration-Cutover §5.2.4)")
    a("--       ปลายทางมี `uq_impact_process UNIQUE (impacted_store_code, impact_month)`")
    a("--       แต่ข้อมูลจริงซ้ำ **17 กลุ่ม** (live 8 · backup 9) → INSERT ตรง ๆ ล้มทั้งทรานแซกชัน")
    a("--       (พิสูจน์แล้วบน dev 2026-09-17: duplicate key ที่ร้าน 02433 งวด 2025-04)")
    a("--       ⚠️ **ห้ามตัด UNIQUE ทิ้ง** — Job 2 ใช้ `ON CONFLICT (impacted_store_code, impact_month)`")
    a("--          ในคำสั่ง upsert (job-2-import-impact-store.service.ts) ตัดแล้ว job พัง")
    a("--       กติกา 3 ชั้น เรียงตามเอกสาร:")
    a("--         1) last_compensate_year/month DESC — แถวที่ก้าวหน้ากว่า")
    a("--         2) create_date ASC — แถว backfill (00:00:00) ชนะแถวที่ job สร้าง (17:00:xx)")
    a("--         3) impact_process_id ASC — กันเสมอ ให้ผล deterministic")
    a("--       ⚠️ ชั้น 3 ยังกันแถวที่ **ซ้ำเป๊ะทั้ง id** ได้ด้วย (backup มี 9 แถว id ซ้ำ ไม่มี PK)")
    a("--       ลูกของแถวที่ถูกตัดเป็นสำเนาซ้ำทั้งหมด (งวด+สถานะตรงกัน 20/20) → หายไปไม่เสียข้อมูล")
    a("-- ---------------------------------------------------------------------")
    a("WITH ranked AS (")
    a("    SELECT p.*, row_number() OVER (")
    a("        PARTITION BY lpad(btrim(p.storecode_i), 5, '0'),")
    a("                     lpad(btrim(p.start_compensate_year), 4, '0') || '-' ||")
    a("                     lpad(btrim(p.start_compensate_month), 2, '0')")
    a("        ORDER BY nullif(btrim(p.last_compensate_year), '')::int  DESC NULLS LAST,")
    a("                 nullif(btrim(p.last_compensate_month), '')::int DESC NULLS LAST,")
    a("                 nullif(btrim(p.create_date), '')::timestamp     ASC  NULLS LAST,")
    a("                 nullif(btrim(p.impact_process_id), '')::bigint  ASC")
    a("    ) AS rn")
    a(f"      FROM {O}fgi_impact_store_on_process p")
    a(")")
    a("INSERT INTO sgi_fgi_impact_processes (")
    a("    id, impacted_store_code, impact_month, impact_year, process_status,")
    a("    workflow_generation_status, last_compensate_seq, last_compensate_seq_no,")
    a("    start_compensate_month, end_compensate_month, flag_action, datasource, updated_by)")
    a("SELECT nullif(btrim(p.impact_process_id), '')::bigint,")
    a("       lpad(btrim(p.storecode_i), 5, '0'),")
    a("       lpad(btrim(p.start_compensate_year), 4, '0') || '-' || lpad(btrim(p.start_compensate_month), 2, '0'),")
    a("       nullif(btrim(p.start_compensate_year), '')::int,")
    a("       'CLOSED',            -- ⚠️ ข้อมูลเดิมเป็นประวัติทั้งหมด · ต้องยืนยันกับธุรกิจ")
    a("       CASE WHEN coalesce(btrim(p.flag_action),'Y') IN ('Y','W','N') THEN coalesce(btrim(p.flag_action),'Y') ELSE 'N' END,")
    a("       coalesce(nullif(btrim(p.last_compensate_seq), '')::int, 1),")
    a("       coalesce(nullif(btrim(p.last_compensate_seq_no), '')::int, 1),")
    a("       lpad(btrim(p.start_compensate_year), 4, '0') || '-' || lpad(btrim(p.start_compensate_month), 2, '0'),")
    a("       CASE WHEN nullif(btrim(p.end_compensate_year), '') IS NULL OR nullif(btrim(p.end_compensate_month), '') IS NULL THEN NULL")
    a("            ELSE lpad(btrim(p.end_compensate_year), 4, '0') || '-' || lpad(btrim(p.end_compensate_month), 2, '0') END,")
    a("       CASE WHEN coalesce(btrim(p.flag_action),'Y') IN ('Y','W','N') THEN coalesce(btrim(p.flag_action),'Y') ELSE 'N' END,")
    a("       nullif(btrim(p.datasource), '')")
    a("       , 'K2-MIGRATION'")
    a("  FROM ranked p")
    a(" WHERE p.rn = 1                       -- ผู้ชนะของแต่ละคู่ (ร้าน, งวดเริ่ม) ตามกติกา 3 ชั้น")
    a("   AND nullif(btrim(p.impact_process_id), '') IS NOT NULL")
    a("   AND nullif(btrim(p.start_compensate_year), '') IS NOT NULL")
    a("   AND nullif(btrim(p.start_compensate_month), '') IS NOT NULL")
    a("   AND EXISTS (SELECT 1 FROM sgi_impacted_stores s")
    a("                WHERE s.store_code = lpad(btrim(p.storecode_i), 5, '0'))")
    a("   AND NOT EXISTS (SELECT 1 FROM sgi_fgi_impact_processes t")
    a("                    WHERE t.id = nullif(btrim(p.impact_process_id), '')::bigint);")
    a("")

    a("-- ---------------------------------------------------------------------")
    a("-- 3. sgi_fgi_impact_compensations ← FGI_IMPACT_STORE_COMPENSATE")
    a("--    ⚠️ ปลายทางเป็นแม่ของ sgi_compensation_documents (impact_compensation_id UNIQUE)")
    a("--    ⚠️ ใส่ id เอง → ต้องดัน sequence ที่ข้อ 6")
    a("-- ---------------------------------------------------------------------")
    a("INSERT INTO sgi_fgi_impact_compensations (")
    a("    id, impact_process_id, impacted_store_code, compensate_seq, compensate_seq_no,")
    a("    compensate_month, compensate_year, forecast_amount, adjust_amount,")
    a("    compensate_status, compensate_comment, stmt_month, stmt_year, approve_date,")
    a("    created_by, updated_by)")
    a("SELECT nullif(btrim(c.compensate_i_id), '')::bigint,")
    a("       nullif(btrim(c.impact_process_id), '')::bigint,")
    a("       lpad(btrim(c.storecode_i), 5, '0'),")
    a("       coalesce(nullif(btrim(c.compensate_seq), '')::int, 1),")
    a("       coalesce(nullif(btrim(c.compensate_seq_no), '')::int, 1),")
    a("       lpad(btrim(c.compensate_year), 4, '0') || '-' || lpad(btrim(c.compensate_month), 2, '0'),")
    a("       nullif(btrim(c.compensate_year), '')::int,")
    a("       coalesce(nullif(btrim(c.compensate_forecast), '')::numeric, 0),")
    a("       nullif(btrim(c.compensate_adjust), '')::numeric,")
    a("       CASE WHEN btrim(c.compensate_status) IN ('I','C','A','N','S','Z') THEN btrim(c.compensate_status) END,")
    a("       nullif(btrim(c.compensate_comment), ''),")
    a("       nullif(btrim(c.stmt_month), '')::int,      -- ⚠️ ปลายทางเป็น INTEGER แยกเดือน/ปี ไม่ใช่ CHAR(7)")
    a("       nullif(btrim(c.stmt_year), '')::int,")
    a("       nullif(btrim(c.approve_date), '')::date,   -- ⚠️ ปลายทางเป็น DATE ไม่ใช่ TIMESTAMP")
    a("       coalesce(nullif(btrim(c.create_by), ''), 'K2-MIGRATION'), nullif(btrim(c.update_by), '')")
    a(f"  FROM {O}fgi_impact_store_compensate c")
    a(" WHERE nullif(btrim(c.compensate_i_id), '') IS NOT NULL")
    a("   AND EXISTS (SELECT 1 FROM sgi_fgi_impact_processes p")
    a("                WHERE p.id = nullif(btrim(c.impact_process_id), '')::bigint)")
    a("   AND NOT EXISTS (SELECT 1 FROM sgi_fgi_impact_compensations t")
    a("                    WHERE t.id = nullif(btrim(c.compensate_i_id), '')::bigint);")
    a("")

    a("-- ---------------------------------------------------------------------")
    a("-- 4. sgi_compensation_documents ← CompensateFlow (K2) ⋈ compensation (Oracle)")
    a("--")
    a("--    🔴 **จุดเชื่อมสองฐาน** — K2 ไม่มี impact_compensation_id จึงต้อง join ด้วย")
    a("--       (รหัสร้าน + ปี + เดือน) ซึ่งเป็นคีย์ธุรกิจร่วมของทั้งสองฝั่ง")
    a("--       ⚠️ ถ้าคู่ (ร้าน, งวด) ซ้ำในฝั่ง Oracle จะได้เอกสารซ้ำ — ตัวนับท้ายไฟล์จับได้")
    a("--")
    a("--    การแปลงสถานะ — ดูหมายเหตุเต็มใน tools/build_k2_migration_sql.py (K2_STATUS_DONE)")
    a(f"--       {K2_STATUS_DONE} → {SGI_STATUS_DONE} · current_section_code = NULL (terminal ไม่มี section)")
    a("--       01/02/03/06/08 → ตรงตัว · current_section_code = section เดิม")
    a("--       04 · 10 · NULL → ไม่มีปลายทาง ข้าม + พิมพ์เลขเอกสารท้ายไฟล์")
    a("--")
    a("--    🔴 round_no ← CompMainLoopNo · loop_no ← CompLoopNo (**คนละมิติกัน ห้ามสลับ**)")
    a("--       หน้าจอแสดง \"รอบ 1 · ครั้งที่ 3\" = (round_no, loop_no)")
    a("--       ของจริงบน dev: main=1,loop=1 มี 8,966 แถว · main=2,loop=1 มี 1,120 · main=1,loop=2 มี 653")
    a("--       รอบก่อนแก้ผิดเป็น round_no ← CompLoopNo ทำให้ uq_comp_business ตัดสินผิดคู่")
    a("--    🔴 running_no ← 5 หลักท้าย doc_no — **ถ้าไม่เติม uq_comp_year_running ไม่ทำงาน**")
    a("--       (NULL ไม่ชนกันใน UNIQUE ของ PostgreSQL) · วัดแล้วไม่ซ้ำสักปี 2019–2026")
    a("-- ---------------------------------------------------------------------")
    a("-- จับคู่เอกสาร ↔ แถวค่าชดเชย แบบ **1:1 เด็ดขาด**")
    a("--   (ร้าน, งวด) ฝั่ง Oracle มี 2 แถวอยู่ 7 กลุ่ม — เกิดจากงวดเดียวกันปรากฏทั้งใน")
    a("--   ตาราง live และตาราง backup · ปล่อยไว้ = เอกสารเดียวถูก INSERT สองครั้ง")
    a("--   (พิสูจน์บน dev 2026-09-17: doc 2025/01286 ชน — ORA id 55166 live กับ 15053 backup)")
    a("--   เลือกแถว **id สูงกว่า** = แถวที่ออกทีหลัง (live) ซึ่งสะท้อนสถานะล่าสุด")
    a("--   ⚠️ ต้องกันซ้ำ **ทั้งสองทาง** เพราะ impact_compensation_id เป็น UNIQUE ฝั่งปลายทางด้วย")
    a("WITH pair AS (")
    a("    -- ⚠️ ตั้งชื่อ alias ขึ้นต้น ora_ ทุกตัว — CompensateFlow มีคอลัมน์ชื่อ `comp_id` อยู่แล้ว")
    a("    --    ใช้ชื่อซ้ำจะได้ 'column reference is ambiguous' (เจอจริง 2026-09-17)")
    a("    SELECT f.*, c.id AS ora_comp_id, c.impact_process_id AS ora_proc_id,")
    a("           c.impacted_store_code AS ora_store_code, c.compensate_month AS ora_month,")
    a("           row_number() OVER (PARTITION BY f.comp_document_id ORDER BY c.id DESC) AS rn_doc,")
    a("           row_number() OVER (PARTITION BY c.id ORDER BY f.comp_document_id) AS rn_comp")
    a(f"      FROM {K}compensate_flow f")
    a("      JOIN sgi_fgi_impact_compensations c")
    a("        ON c.impacted_store_code = lpad(btrim(f.comp_store_code), 5, '0')")
    a("       AND c.compensate_month = lpad(btrim(f.comp_year), 4, '0') || '-' || lpad(btrim(f.comp_month), 2, '0')")
    a("     WHERE " + doc_migratable("f"))
    a(")")
    a("INSERT INTO sgi_compensation_documents (")
    a("    doc_no, year, running_no, impact_process_id, impact_compensation_id, impacted_store_code,")
    a("    impact_month, round_no, loop_no, source, status_code, current_section_code,")
    a("    total_compensation_amount, allmap_url, statement_id,")
    a("    account_year, account_month, approver_snapshot, created_by)")
    a("SELECT f.comp_document_id,")
    a("       left(f.comp_document_id, 4)::int,")
    a("       right(f.comp_document_id, 5)::int,          -- running_no (เติม 2026-09-17)")
    a("       f.ora_proc_id, f.ora_comp_id, f.ora_store_code,")
    a("       f.ora_month,")
    a("       coalesce(nullif(btrim(f.comp_main_loop_no), '')::int, 1),   -- round_no  ← CompMainLoopNo")
    a("       nullif(btrim(f.comp_loop_no), '')::int,                     -- loop_no   ← CompLoopNo")
    a("       CASE WHEN btrim(f.comp_type) = '04' THEN 'MANUAL' ELSE 'FS' END,")
    a(f"       CASE WHEN f.comp_status_code = '{K2_STATUS_DONE}' THEN '{SGI_STATUS_DONE}'")
    a("            ELSE f.comp_status_code END,")
    a(f"       CASE WHEN f.comp_status_code = '{K2_STATUS_DONE}' THEN NULL   -- terminal ไม่มี section")
    a("            ELSE f.comp_section_code END,")
    a("       coalesce(nullif(btrim(f.comp_actual), '')::numeric,")
    a("                nullif(btrim(f.comp_forecast), '')::numeric, 0),")
    a("       nullif(btrim(f.comp_url_map), ''), nullif(btrim(f.comp_statement_id), ''),")
    a("       nullif(btrim(f.comp_account_year), '')::int,")
    a("       nullif(btrim(f.comp_account_month), '')::int,               -- account_month (เติม 2026-09-17)")
    a("       -- approver_snapshot — เก็บผู้เกี่ยวข้อง ณ เวลาเปิดเอกสารไว้เป็นหลักฐาน")
    a("       --   ⚠️ FC และ Section **ว่างทั้ง 18,007 แถวบน dev** จึงไม่ใส่ (jsonb_strip_nulls ตัดให้)")
